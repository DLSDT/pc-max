import i18n from 'i18next';
import { initReactI18next } from 'react-i18next';

/**
 * Read the persisted language choice (store/ui.ts, zustand `persist` under
 * `goh_ui`) synchronously, before i18next initializes and before React ever
 * renders. Without this, i18next always boots at the hardcoded fallback
 * below and the UI briefly (or, on a fresh mount before Settings runs
 * `changeLanguage`, permanently) shows English/LTR even when the user
 * previously chose Persian — the app never re-reads the saved preference on
 * startup, only reacting to a live change from the Settings page.
 */
function loadPersistedLanguage(): 'en' | 'fa' {
  try {
    const raw = localStorage.getItem('goh_ui');
    if (!raw) return 'en';
    const parsed = JSON.parse(raw) as { state?: { language?: string } };
    return parsed.state?.language === 'fa' ? 'fa' : 'en';
  } catch {
    return 'en';
  }
}

